#!/usr/bin/env python3
"""
Build the Pixels to Metro Policy landing page.

Produces two outputs from src/ + data/ (no CDN or network dependencies):

  dist/web/          Multi-file version for integrating into the main website
                     index.html, css/, js/ (incl. p2m-data.js), img/
  dist/standalone/   One self-contained index.html (same page, everything inlined)

Usage
  python3 build.py
  python3 build.py --platform-url https://example.org/platform
  python3 build.py --platform-url /platform --out dist

--platform-url sets every "Platform →" / "Open the Urban Intelligence Platform"
link (the "next page"). Defaults to "#platform" so it is obvious what to replace.

Only the Python standard library is needed.
"""
import argparse, base64, json, os, re, shutil

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC, DATA = os.path.join(ROOT, "src"), os.path.join(ROOT, "data")
DATA_KEYS = ["popbars", "landdots", "w110", "sea10", "bkk"]


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def write(p, s):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8") as f:
        f.write(s)


def load_data():
    return {k: json.loads(read(os.path.join(DATA, k + ".json"))) for k in DATA_KEYS}


def split_images(data, img_dir, url_prefix):
    """Move base64 images in bkk.json (model heat layer, roof segmentation) to files."""
    for key, name in (("heat", "p2m-model-heat"), ("seg", "p2m-roof-segmentation"), ("hz", "p2m-flood-hazard"), ("dens", "p2m-density-2564"), ("segGoogle", "p2m-roof-segmentation-google")):
        uri = data["bkk"].get(key, "")
        m = re.match(r"data:image/(\w+);base64,(.*)", uri, re.S)
        if not m:
            continue
        ext = {"jpeg": "jpg"}.get(m.group(1), m.group(1))
        fn = f"{name}.{ext}"
        os.makedirs(img_dir, exist_ok=True)
        with open(os.path.join(img_dir, fn), "wb") as f:
            f.write(base64.b64decode(m.group(2)))
        data["bkk"][key] = url_prefix + fn


def data_js(data):
    body = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    return "/* Pixels to Metro Policy · page data (generated by build.py) */\nwindow.P2M_DATA=" + body + ";\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--platform-url", default="#platform")
    ap.add_argument("--out", default=os.path.join(ROOT, "dist"))
    a = ap.parse_args()

    html = read(os.path.join(SRC, "index.template.html")).replace("__P2MP__", a.platform_url)
    MEDIA = os.path.join(SRC, "media")
    def media_inline(s):
        def sub(m):
            fn = m.group(1); ext = fn.rsplit(".", 1)[1]
            mt = {"mp4": "video/mp4", "webm": "video/webm", "jpg": "image/jpeg", "png": "image/png", "webp": "image/webp"}[ext]
            with open(os.path.join(MEDIA, fn), "rb") as f:
                return f"data:{mt};base64," + base64.b64encode(f.read()).decode()
        return re.sub(r"__MEDIA:([^_][^\s\"]*?)__", sub, s)
    css = read(os.path.join(SRC, "p2m-landing.css"))
    js_voyage = read(os.path.join(SRC, "p2m-voyage.js"))
    js_scene = read(os.path.join(SRC, "p2m-scene.js"))

    # ---- multi-file web build
    web = os.path.join(a.out, "web")
    shutil.rmtree(web, ignore_errors=True)
    data = load_data()
    split_images(data, os.path.join(web, "img"), "img/")
    write(os.path.join(web, "index.html"), re.sub(r"__MEDIA:([^\s\"]*?)__", r"media/\1", html))
    if os.path.isdir(MEDIA):
        shutil.copytree(MEDIA, os.path.join(web, "media"), dirs_exist_ok=True)
    write(os.path.join(web, "css", "p2m-landing.css"), css)
    write(os.path.join(web, "js", "p2m-voyage.js"), js_voyage)
    write(os.path.join(web, "js", "p2m-scene.js"), js_scene)
    write(os.path.join(web, "js", "p2m-data.js"), data_js(data))
    shutil.copytree(os.path.join(SRC, "vendor"), os.path.join(web, "js", "vendor"), dirs_exist_ok=True)
    shutil.copytree(os.path.join(SRC, "fonts"), os.path.join(web, "fonts"), dirs_exist_ok=True)
    write(os.path.join(web, "css", "fonts.css"), read(os.path.join(SRC, "fonts.css")))

    # ---- single-file standalone build
    std = os.path.join(a.out, "standalone")
    shutil.rmtree(std, ignore_errors=True)
    data = load_data()  # images stay inline
    safe = lambda s: s.replace("</script", "<\\/script")
    one = media_inline(html)
    one = one.replace('<link rel="stylesheet" href="css/p2m-landing.css">', "<style>\n" + css + "</style>")
    fcss = re.sub(r"url\(\.\./fonts/([^)]+)\)", lambda m: "url(data:font/woff2;base64," + base64.b64encode(open(os.path.join(SRC, "fonts", m.group(1)), "rb").read()).decode() + ")", read(os.path.join(SRC, "fonts.css")))
    one = one.replace('<link rel="stylesheet" href="css/fonts.css">', "<style>\n" + fcss + "</style>")
    for lib in ("d3.min.js", "topojson-client.min.js"):
        one = one.replace(f'<script src="js/vendor/{lib}"></script>', "<script>" + safe(read(os.path.join(SRC, "vendor", lib))) + "</script>")
    one = one.replace('<script src="js/p2m-data.js"></script>', "<script>" + safe(data_js(data)) + "</script>")
    one = one.replace('<script src="js/p2m-voyage.js"></script>', "<script>\n" + safe(js_voyage) + "</script>")
    one = one.replace('<script src="js/p2m-scene.js"></script>', "<script>\n" + safe(js_scene) + "</script>")
    write(os.path.join(std, "index.html"), one)

    for root, _, files in os.walk(a.out):
        for f in sorted(files):
            p = os.path.join(root, f)
            print(f"{os.path.relpath(p, a.out):45s} {os.path.getsize(p)/1024:9.1f} KB")
    print("platform link ->", a.platform_url)


if __name__ == "__main__":
    main()
